import API from "../../api";

/*
|--------------------------------------------------------------------------
| LIST
|--------------------------------------------------------------------------
*/
export const getDoctors = (params) =>
    API.get("/admin/view/doctors", { params });

/*
|--------------------------------------------------------------------------
| CREATE
|--------------------------------------------------------------------------
*/
export const createDoctor = (data) =>
    API.post("/admin/control/doctors/add", data);

/*
|--------------------------------------------------------------------------
| UPDATE
|--------------------------------------------------------------------------
*/
export const updateDoctor = (id, data) =>
    API.put(`/admin/control/doctors/update/${id}`, data);

/*
|--------------------------------------------------------------------------
| DELETE
|--------------------------------------------------------------------------
*/
export const deleteDoctor = (id) =>
    API.delete(`/admin/control/doctors/delete/${id}`);